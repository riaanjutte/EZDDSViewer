def _is_newer_version(remote: str, local: str) -> bool:
    """Compare dot-separated version strings (e.g. '1.2.3'). Returns True if
    remote > local. Non-numeric segments fall back to lexicographic compare."""
    def parts(s):
        out = []
        for seg in s.strip().lstrip("v").split("."):
            try:
                out.append((0, int(seg)))
            except ValueError:
                out.append((1, seg))
        return out
    return parts(remote) > parts(local)


def _has_dds_url(event) -> bool:
    md = event.mimeData()
    return md.hasUrls() and any(
        u.toLocalFile().lower().endswith('.dds') for u in md.urls()
    )



class ImageViewer(QGraphicsView):
    pixel_hovered = Signal(int, int)
    pixel_left    = Signal()
    file_dropped  = Signal(str)
    activated     = Signal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setMouseTracking(True)
        self._scene = QGraphicsScene(self)
        self.setScene(self._scene)
        self._pixmap_item = None
        self._zoom = 1.0
        self._user_zoomed = False
        self._peer: 'ImageViewer | None' = None
        self._syncing = False

        self.setDragMode(QGraphicsView.DragMode.ScrollHandDrag)
        self.setTransformationAnchor(QGraphicsView.ViewportAnchor.AnchorUnderMouse)
        self.setResizeAnchor(QGraphicsView.ViewportAnchor.AnchorUnderMouse)
        self.setRenderHint(QPainter.RenderHint.Antialiasing, False)
        self.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform, False)
        self.setBackgroundBrush(self._make_checker_brush())
        self.setInteractive(True)
        self.setAcceptDrops(True)

        self.horizontalScrollBar().valueChanged.connect(self._on_scroll)
        self.verticalScrollBar().valueChanged.connect(self._on_scroll)

    @staticmethod
    def _make_checker_brush() -> QBrush:
        tile = QPixmap(CHECKER_SIZE * 2, CHECKER_SIZE * 2)
        tile.fill(CHECKER_LIGHT)
        p = QPainter(tile)
        p.fillRect(0, 0, CHECKER_SIZE, CHECKER_SIZE, CHECKER_DARK)
        p.fillRect(CHECKER_SIZE, CHECKER_SIZE, CHECKER_SIZE, CHECKER_SIZE, CHECKER_DARK)
        p.end()
        return QBrush(tile)

    def set_peer(self, peer: 'ImageViewer | None'):
        self._peer = peer

    def _sync_to_peer(self):
        if self._peer and not self._syncing:
            self._peer._apply_sync(
                self.transform(),
                self.horizontalScrollBar().value(),
                self.verticalScrollBar().value(),
            )

    def _apply_sync(self, transform, hval: int, vval: int):
        self._syncing = True
        self._user_zoomed = True
        self.setTransform(transform)
        self.horizontalScrollBar().setValue(hval)
        self.verticalScrollBar().setValue(vval)
        self._syncing = False

    def _on_scroll(self):
        self._sync_to_peer()

    def set_pixmap(self, pixmap: QPixmap):
        self._scene.clear()
        self._pixmap_item = self._scene.addPixmap(pixmap)
        self._scene.setSceneRect(QRectF(pixmap.rect()))

    def heightForWidth(self, width: int) -> int:
        return width

    def hasHeightForWidth(self) -> bool:
        return True

    def fit_in_view(self):
        if self._pixmap_item:
            self._user_zoomed = False
            self.fitInView(self._pixmap_item, Qt.AspectRatioMode.KeepAspectRatio)
            self._sync_to_peer()

    def zoom_actual(self):
        self._user_zoomed = True
        self.resetTransform()
        self._sync_to_peer()

    def resizeEvent(self, event):
        super().resizeEvent(event)
        if not self._user_zoomed:
            self.fit_in_view()

    def mouseMoveEvent(self, event: QMouseEvent):
        super().mouseMoveEvent(event)
        if self._pixmap_item:
            scene_pt = self.mapToScene(event.position().toPoint())
            bounding = self._pixmap_item.boundingRect()
            if bounding.contains(scene_pt):
                self.pixel_hovered.emit(int(scene_pt.x()), int(scene_pt.y()))
            else:
                self.pixel_left.emit()

    def leaveEvent(self, event):
        super().leaveEvent(event)
        self.pixel_left.emit()

    def dragEnterEvent(self, event: QDragEnterEvent):
        if _has_dds_url(event):
            event.acceptProposedAction()
        else:
            event.ignore()

    def dragMoveEvent(self, event):
        if _has_dds_url(event):
            event.acceptProposedAction()
        else:
            event.ignore()

    def dropEvent(self, event: QDropEvent):
        for url in event.mimeData().urls():
            path = url.toLocalFile()
            if path.lower().endswith('.dds'):
                self.file_dropped.emit(path)
                event.acceptProposedAction()
                break

    def wheelEvent(self, event: QWheelEvent):
        self._user_zoomed = True
        factor = 1.25 if event.angleDelta().y() > 0 else 0.8
        self.scale(factor, factor)
        self._sync_to_peer()

    def mousePressEvent(self, event: QMouseEvent):
        self.activated.emit()
        super().mousePressEvent(event)


