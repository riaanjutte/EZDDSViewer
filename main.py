    def load_file(self, path: str):
        try:
            data = Path(path).read_bytes()
            info, mipmaps = parse_dds(data)
        except Exception as exc:
            QMessageBox.critical(self, "Error loading DDS", str(exc))
            return

        self._push_recent(path)
        self._current_path = path
        self._mipmaps = mipmaps
        self._info = info
        self._current_mip_l = 0
        self._channel_l = 'RGB'
        self._update_nav_buttons()

        self.setWindowTitle(f"{APP_TITLE} — {os.path.basename(path)}")
        self._last_status = (
            f"{path}  |  {info.format_name}  |  {info.width}×{info.height}"
            f"  |  {info.mip_count} mip{'s' if info.mip_count != 1 else ''}"
            f"  |  {info.file_size / 1024:.1f} KB"
        )
        self.status.showMessage(self._last_status)
        self._refresh_image()
        self._set_active_side(1)
        self.viewer.fit_in_view()

    def load_file2(self, path: str):
        try:
            data = Path(path).read_bytes()
            info, mipmaps = parse_dds(data)
        except Exception as exc:
            QMessageBox.critical(self, "Error loading DDS", str(exc))
            return
        self._current_path2 = path
        self._mipmaps2 = mipmaps
        self._info2 = info
        self._current_mip_r = 0
        self._channel_r = 'RGB'
        self._update_nav_buttons()
        self._refresh_image2()
        self._set_active_side(2)
        self.viewer2.fit_in_view()

    # ── Folder navigation ─────────────────────────────────────────────────────

    def _folder_dds_files(self, path: str) -> list[str]:
        folder = Path(path).parent
        try:
            files = [p for p in folder.iterdir()
                     if p.is_file() and p.suffix.lower() == '.dds']
        except OSError:
            return []
        files.sort(key=lambda p: p.name.lower())
        return [str(p) for p in files]

    def _side_current(self, which: int) -> str | None:
        return self._current_path if which == 1 else self._current_path2

    def _side_loader(self, which: int):
        return self.load_file if which == 1 else self.load_file2

    def _navigate_side(self, which: int, delta: int):
        current = self._side_current(which)
        if not current:
            return
        files = self._folder_dds_files(current)
        if not files:
            return
        try:
            idx = files.index(current)
        except ValueError:
            idx = 0
            delta = 0
        new_idx = (idx + delta) % len(files)
        self._side_loader(which)(files[new_idx])

    def _delete_side(self, which: int):
        path = self._side_current(which)
        if not path:
            return
        if self.chk_confirm_delete.isChecked():
            reply = QMessageBox.question(
                self, "Delete File",
                f"Delete '{os.path.basename(path)}'?\n\nThis cannot be undone.",
                QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                QMessageBox.StandardButton.No,
            )
            if reply != QMessageBox.StandardButton.Yes:
                return

        files = self._folder_dds_files(path)
        try:
            idx = files.index(path)
        except ValueError:
            idx = -1

        try:
            os.remove(path)
        except OSError as exc:
            QMessageBox.critical(self, "Delete failed", str(exc))
            return

        remaining = [p for p in files if p != path]
        if remaining:
            next_idx = min(idx, len(remaining) - 1) if idx >= 0 else 0
            self._side_loader(which)(remaining[next_idx])
            self.status.showMessage(f"Deleted {os.path.basename(path)}")
        else:
            self._clear_side(which)
            self.status.showMessage(f"Deleted {os.path.basename(path)}  (folder empty)")

    def _clear_side(self, which: int):
        if which == 1:
            self._mipmaps = []
            self._info = None
            self._current_path = None
            self.viewer._scene.clear()
            self.viewer._pixmap_item = None
            self.setWindowTitle(APP_TITLE)
            self._last_status = ""
        else:
            self._mipmaps2 = []
            self._info2 = None
            self._current_path2 = None
            self.viewer2._scene.clear()
            self.viewer2._pixmap_item = None
        self._update_nav_buttons()
        if self._active_side == which:
            self._sync_sidebar_to_active()

    def _update_nav_buttons(self):
        left = bool(self._current_path)
        self.btn_prev_l.setEnabled(left)
        self.btn_next_l.setEnabled(left)
        self.btn_del_l.setEnabled(left)
        right = bool(self._current_path2)
        self.btn_prev_r.setEnabled(right)
        self.btn_next_r.setEnabled(right)
        self.btn_del_r.setEnabled(right)

    def _active_viewer(self) -> 'ImageViewer':
        return self.viewer if self._active_side == 1 else self.viewer2

    def _set_active_side(self, side: int):
        self._active_side = side
        self._update_active_styling()
        self._sync_sidebar_to_active()

    def _update_active_styling(self):
        active_border = "2px solid #3584e4"
        inactive_border = "2px solid transparent"
        if self._split_mode:
            l = active_border if self._active_side == 1 else inactive_border
            r = active_border if self._active_side == 2 else inactive_border
        else:
            l = r = inactive_border
        self._frame_l.setStyleSheet(f"#viewerFrame1 {{ border: {l}; }}")
        self._frame_r.setStyleSheet(f"#viewerFrame2 {{ border: {r}; }}")

    def _sync_sidebar_to_active(self):
        info = self._info if self._active_side == 1 else self._info2
        path = self._current_path if self._active_side == 1 else self._current_path2
        mip_val = self._current_mip_l if self._active_side == 1 else self._current_mip_r
        channel = self._channel_l if self._active_side == 1 else self._channel_r

        if info and path:
            self.lbl_size.setText(f"{info.width} × {info.height}")
            self.lbl_fmt.setText(info.format_name)
            self.lbl_mips.setText(str(info.mip_count))
            self.lbl_alpha.setText("Yes" if info.has_alpha else "No")
            self.lbl_file.setText(os.path.basename(path))
        else:
            self.lbl_size.setText("—")
            self.lbl_fmt.setText("—")
            self.lbl_mips.setText("—")
            self.lbl_alpha.setText("—")
            self.lbl_file.setText("—")

        self.mip_slider.blockSignals(True)
        self._update_mip_range()
        self.mip_slider.setValue(mip_val)
        self.mip_slider.blockSignals(False)
        self._update_mip_label(mip_val)

        if channel in self._chan_buttons:
            self._chan_buttons[channel].setChecked(True)

    # ── Split view ────────────────────────────────────────────────────────────

    def _toggle_split(self, checked: bool):
        self._split_mode = checked
        if checked:
            self._right_panel.show()
            self.btn_open_l.setText("Open Left…")
            self.chk_mirror.setEnabled(True)
            self._splitter.setSizes([self._splitter.width() // 2,
                                     self._splitter.width() // 2])
            self._apply_mirror(self.chk_mirror.isChecked())
        else:
            self._right_panel.hide()
            self.btn_open_l.setText("Open…")
            self.viewer.set_peer(None)
            self.viewer2.set_peer(None)
            self.chk_mirror.setEnabled(False)
            self._set_active_side(1)
        self._update_active_styling()

    def _on_mirror_toggled(self, enabled: bool):
        if self._split_mode:
            self._apply_mirror(enabled)

    def _apply_mirror(self, enabled: bool):
        if enabled:
            self.viewer.set_peer(self.viewer2)
            self.viewer2.set_peer(self.viewer)
        else:
            self.viewer.set_peer(None)
            self.viewer2.set_peer(None)

    # ── Display ──────────────────────────────────────────────────────────────

    def _update_mip_range(self):
        src = self._mipmaps if self._active_side == 1 else self._mipmaps2
        self.mip_slider.setMaximum(max(0, len(src) - 1))

    def _on_mip_changed(self, value: int):
        if self._active_side == 1:
            self._current_mip_l = value
        else:
            self._current_mip_r = value
        self._update_mip_label(value)
        if self._active_side == 1:
            self._refresh_image()
        else:
            self._refresh_image2()

    def _update_mip_label(self, level: int):
        src = self._mipmaps if self._active_side == 1 else self._mipmaps2
        if src:
            clamped = min(level, len(src) - 1)
            h, w = src[clamped].shape[:2]
            self.mip_label.setText(f"Level {level}  ({w}×{h})")

    def _set_channel(self, key: str):
        if self._active_side == 1:
            self._channel_l = key
            self._refresh_image()
        else:
            self._channel_r = key
            self._refresh_image2()

    def _refresh_image(self):
        if not self._mipmaps:
            return
        level = min(self._current_mip_l, len(self._mipmaps) - 1)
        mip = self._mipmaps[level]
        img = self._apply_channel(mip, self._channel_l)
        h, w = img.shape[:2]
        qimg = QImage(img.tobytes(), w, h, w * 4, QImage.Format.Format_RGBA8888)
        self.viewer.set_pixmap(QPixmap.fromImage(qimg))

    def _refresh_image2(self):
        if not self._mipmaps2:
            return
        level = min(self._current_mip_r, len(self._mipmaps2) - 1)
        mip = self._mipmaps2[level]
        img = self._apply_channel(mip, self._channel_r)
        h, w = img.shape[:2]
        qimg = QImage(img.tobytes(), w, h, w * 4, QImage.Format.Format_RGBA8888)
        self.viewer2.set_pixmap(QPixmap.fromImage(qimg))

    def _apply_channel(self, src: np.ndarray, ch: str) -> np.ndarray:
        img = src.copy()
        if ch == 'RGB':
            img[:, :, 3] = 255
        elif ch == 'R':
            r = img[:, :, 0].copy()
            img[:] = 0
            img[:, :, 0] = r
            img[:, :, 3] = 255
        elif ch == 'G':
            g = img[:, :, 1].copy()
            img[:] = 0
            img[:, :, 1] = g
            img[:, :, 3] = 255
        elif ch == 'B':
            b = img[:, :, 2].copy()
            img[:] = 0
            img[:, :, 2] = b
            img[:, :, 3] = 255
        elif ch == 'A':
            a = img[:, :, 3].copy()
            img[:, :, 0] = a
            img[:, :, 1] = a
            img[:, :, 2] = a
            img[:, :, 3] = 255
        return img

    # ── Pixel inspector ──────────────────────────────────────────────────────

    def _on_pixel_hovered(self, x: int, y: int, which: int):
        if which == 1:
            mipmaps = self._mipmaps
            current = self._current_mip_l
        else:
            mipmaps = self._mipmaps2
            current = self._current_mip_r
        if not mipmaps:
            return
        level = min(current, len(mipmaps) - 1)
        mip = mipmaps[level]
        h, w = mip.shape[:2]
        if 0 <= x < w and 0 <= y < h:
            r, g, b, a = mip[y, x]
            self.status.showMessage(
                f"X {x}  Y {y}    R {r}  G {g}  B {b}  A {a}"
                f"    #{r:02X}{g:02X}{b:02X}{a:02X}"
            )

    def _on_pixel_left(self):
        if self._info:
            self.status.showMessage(self._last_status)

    # ── Export ───────────────────────────────────────────────────────────────

    def _export_png(self):
        if self._active_side == 1:
            mipmaps = self._mipmaps
            current_mip = self._current_mip_l
            channel = self._channel_l
            src_path = self._current_path
        else:
            mipmaps = self._mipmaps2
            current_mip = self._current_mip_r
            channel = self._channel_r
            src_path = self._current_path2
        if not mipmaps:
            QMessageBox.information(self, "Export", "No image loaded.")
            return
        stem = os.path.splitext(os.path.basename(src_path))[0] if src_path else "export"
        mip_suffix = f"_mip{current_mip}" if current_mip > 0 else ""
        ch_suffix = f"_{channel}" if channel != "RGB" else ""
        default_name = f"{stem}{mip_suffix}{ch_suffix}.png"
        last_dir = self._settings().value("lastDir", "")
        path, _ = QFileDialog.getSaveFileName(
            self, "Export as PNG", os.path.join(last_dir, default_name),
            "PNG Files (*.png)",
        )
        if not path:
            return
        level = min(current_mip, len(mipmaps) - 1)
        mip = mipmaps[level]
        img = self._apply_channel(mip, channel)
        h, w = img.shape[:2]
        qimg = QImage(img.tobytes(), w, h, w * 4, QImage.Format.Format_RGBA8888)
        if qimg.save(path, "PNG"):
            self.status.showMessage(f"Exported → {path}")
        else:
            QMessageBox.critical(self, "Export failed", f"Could not write {path}")

    # ── Drag & drop (title bar / window edges fallback) ───────────────────────

    def dragEnterEvent(self, event: QDragEnterEvent):
        if _has_dds_url(event):
            event.acceptProposedAction()
        else:
            event.ignore()

    def dragMoveEvent(self, event):
        if _has_dds_url(event):
            event.acceptProposedAction()
        else:
            event.ignore()

    def dropEvent(self, event: QDropEvent):
        for url in event.mimeData().urls():
            path = url.toLocalFile()
            if path.lower().endswith('.dds'):
                self.load_file(path)
                event.acceptProposedAction()
                break

    # ── Window geometry persistence ───────────────────────────────────────────

    def _settings(self) -> QSettings:
        return QSettings("EZDDSViewer", "EZDDSViewer")

    def _restore_geometry(self):
        s = self._settings()
        geom = s.value("geometry")
        if isinstance(geom, QByteArray):
            self.restoreGeometry(geom)

    def closeEvent(self, event):
        self._settings().setValue("geometry", self.saveGeometry())
        super().closeEvent(event)


