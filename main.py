    # ── Recent files ─────────────────────────────────────────────────────────

    def _recent_paths(self) -> list[str]:
        val = self._settings().value("recentFiles", [])
        return val if isinstance(val, list) else []

    def _push_recent(self, path: str):
        paths = [p for p in self._recent_paths() if p != path]
        paths.insert(0, path)
        self._settings().setValue("recentFiles", paths[:self._MAX_RECENT])
        self._rebuild_recent_menu()

    def _rebuild_recent_menu(self):
        self._recent_menu.clear()
        paths = self._recent_paths()
        if not paths:
            self._recent_menu.addAction("(empty)").setEnabled(False)
            return
        for path in paths:
            act = QAction(os.path.basename(path), self)
            act.setToolTip(path)
            act.triggered.connect(lambda checked, p=path: self.load_file(p))
            self._recent_menu.addAction(act)
        self._recent_menu.addSeparator()
        clear_act = QAction("Clear Recent", self)
        clear_act.triggered.connect(self._clear_recent)
        self._recent_menu.addAction(clear_act)

    def _clear_recent(self):
        self._settings().setValue("recentFiles", [])
        self._rebuild_recent_menu()

